use std::cell::RefCell;

use ecow::EcoVec;
use serde::{Deserialize, Serialize};

use crate::time::{TDuration, TTime};
use crate::{IntervalCollection, NodeKey};

/// Travel mode. Travel mode defines how the vehicle travels.
#[derive(Clone, Serialize, Deserialize, Copy, Debug, PartialEq)]
pub enum TravelMode {
    At(TTime),
    For(TDuration),
    Flexible,
}

#[derive(Clone, Serialize, Deserialize, Copy, Debug, PartialEq)]
pub struct TEntryId(u32);

impl TEntryId {
    /// Create a new unique entry ID.
    pub fn new() -> Self {
        use std::sync::atomic::{AtomicU32, Ordering};
        static NEXT: AtomicU32 = AtomicU32::new(1);
        Self(NEXT.fetch_add(1, Ordering::Relaxed))
    }
}

/// An entry in the schedule. `TEntry` is short for `TimetableEntry`.
///
/// The schedule conatins an ordered list of entries. There are two categories for an entry:
/// `derived`, which is automatically generated by the system and may be invalidated, and `pinned`,
/// which can be only generated by sending explicit [`crate::Command`]s.
///
/// `derived` and `pinned` entries have different semantics. A derived entry may or may not visit
/// the station, while a pinned entry must visit the station. Each pinned entry has an ID.
#[derive(Clone, Serialize, Deserialize, Copy, Debug, PartialEq)]
pub enum TEntry {
    /// A derived state. this is calculated by the system.
    Derived { node: NodeKey, id: TEntryId },
    /// A pinned station. The trip must visit this station.
    /// This requires runtime checks to make sure that the start and end are valid.
    Pinned {
        node: NodeKey,
        arr: TravelMode,
        dep: TravelMode,
        external: bool,
        id: TEntryId,
    },
    /// A pinned station. The trip must visit this station,
    /// but the vehicle does not stop at the station.
    PinnedNonStop {
        node: NodeKey,
        pass: TravelMode,
        external: bool,
        id: TEntryId,
    },
}

impl TEntry {
    pub fn node_key(&self) -> NodeKey {
        match self {
            Self::Derived { node, .. } => *node,
            Self::Pinned { node, .. } => *node,
            Self::PinnedNonStop { node, .. } => *node,
        }
    }
}

#[derive(Clone, Serialize, Deserialize, PartialEq, Debug)]
pub struct TripSchedule {
    entries: EcoVec<TEntry>,
}

impl TripSchedule {
    pub fn new(entries: EcoVec<TEntry>) -> Self {
        Self { entries }
    }

    /// The schedule entries.
    pub fn entries(&self) -> &[TEntry] {
        &self.entries
    }

    /// Mutable access to the schedule entries.
    pub fn entries_mut(&mut self) -> &mut EcoVec<TEntry> {
        &mut self.entries
    }
}

#[derive(Clone, Copy)]
struct TEstimate {
    arr: TTime,
    dep: TTime,
}

impl TEstimate {
    fn duration(self) -> TDuration {
        self.dep - self.arr
    }
}

struct EstimateSketch {
    node: NodeKey,
    slot: usize,
    dur: TDuration,
}

// stupid design to avoid allocations...
thread_local! {
    static ESTIMATE_BUFFER: RefCell<Vec<EstimateSketch>> = RefCell::new(Vec::with_capacity(100));
    static OUTPUT_BUFFER: RefCell<Vec<(Option<TEstimate>, TEntry)>> = RefCell::new(Vec::with_capacity(100));
}

enum StackElem {
    Ignored,
    In(NodeKey, TDuration),
    AtAt(NodeKey, TTime, TTime),
    ForAt(NodeKey, TDuration, TTime),
    ForFor(NodeKey, TDuration, TDuration),
}

impl TripSchedule {
    fn estimates<F, R>(&self, intervals: &IntervalCollection, mut f: F) -> R
    where
        F: FnMut(&[(Option<TEstimate>, TEntry)]) -> R,
    {
        ESTIMATE_BUFFER.with(|r| {
            let mut estimate_buf = r.borrow_mut();
            estimate_buf.clear();
            OUTPUT_BUFFER.with(|r| {
                let mut output_buf = r.borrow_mut();
                output_buf.clear();
                for entry in &self.entries {
                    let se = make_se(*entry);
                    match se {
                        StackElem::Ignored => {
                            output_buf.push((None, *entry));
                        }
                        StackElem::In(node, dur) => {
                            let es = EstimateSketch {
                                node,
                                slot: estimate_buf.len(),
                                dur,
                            };
                            estimate_buf.push(es);
                        }
                        // unwind
                        StackElem::AtAt(node, at, dt) => {}
                        StackElem::ForAt(node, ad, dt) => {}
                        StackElem::ForFor(node, ad, dd) => {}
                    };
                }
                // finalize
                f(output_buf.as_slice())
            })
        })
    }
}

fn make_se(entry: TEntry) -> StackElem {
    use StackElem as Se;
    use TravelMode as Tm;
    match entry {
        TEntry::Derived { node, .. } => Se::In(node, TDuration::ZERO),
        TEntry::Pinned { external, .. } if external => Se::Ignored,
        TEntry::PinnedNonStop { external, .. } if external => Se::Ignored,
        TEntry::Pinned { node, arr, dep, .. } => match (arr, dep) {
            (Tm::At(at), Tm::At(dt)) => Se::AtAt(node, at, dt),
            (Tm::At(at), Tm::For(dd)) => Se::AtAt(node, at, at + dd),
            (Tm::At(at), Tm::Flexible) => Se::AtAt(node, at, at),
            (Tm::For(ad), Tm::At(dt)) => Se::ForAt(node, ad, dt),
            (Tm::For(ad), Tm::For(dd)) => Se::ForFor(node, ad, dd),
            (Tm::For(ad), Tm::Flexible) => Se::ForFor(node, ad, TDuration::ZERO),
            (Tm::Flexible, Tm::At(dt)) => Se::AtAt(node, dt, dt),
            (Tm::Flexible, Tm::For(dd)) => Se::In(node, dd),
            (Tm::Flexible, Tm::Flexible) => Se::In(node, TDuration::ZERO),
        },
        TEntry::PinnedNonStop { node, .. } => Se::In(node, TDuration::ZERO),
    }
}
